def decode_prompt() -> str:
    """把内嵌的 base64 解回 UTF-8 正文；解码失败或正文全空白时抛 ValueError。"""
    try:
        data = base64.b64decode("".join(PROMPT_B64.split()), validate=True)
    except binascii.Error as exc:
        raise ValueError(f"内嵌 base64 损坏：{exc}") from None
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ValueError(f"base64 内容不是合法的 UTF-8：{exc}") from None
    if not text.strip():
        raise ValueError("解码后的正文为空")
    return text


def write_prompt(text: str, path: pathlib.Path) -> None:
    """原子写入：先写同目录临时文件再 ``os.replace``，避免读到半个文件。

    ``newline=""`` 让 ``\n`` 原样落盘，不做平台相关的换行转换。``mkstemp``
    建出来的是 ``0600``，所以这里继承原文件权限（原文件不存在时用 ``0644``），
    别让重新生成把文件悄悄改成只有本人可读。
    """
    try:
        mode = stat.S_IMODE(path.stat().st_mode)
    except OSError:
        mode = 0o644
    fd, tmp_name = tempfile.mkstemp(dir=str(path.parent), prefix=".prompt.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.chmod(tmp_name, mode)
        os.replace(tmp_name, path)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except OSError:
            pass
        raise


def load_prompt() -> int:
    """注入钩子：解码 base64 → 生成 prompt.md。成功返回 0，失败返回 1。"""
    # 用 __file__ 而不是 cwd：钩子虽然以模板目录为 cwd 运行，显式定位更稳，
    # 手工调试时也不会写错目录。
    target = pathlib.Path(__file__).resolve().with_name(PROMPT_FILENAME)
    try:
        text = decode_prompt()
        write_prompt(text, target)
    except (ValueError, OSError) as exc:
        print(f"ds-purge: 生成 {PROMPT_FILENAME} 失败：{exc}", file=sys.stderr)
        return 1
    print(f"ds-purge: 已生成 {target}（{len(text)} 字符）")
    return 0


